% 例程 2.12  牛顿-拉夫逊法求解函数极小值
%  函数：y = 5x - log(x);
%  第一步：绘制函数曲线
x = 0.01: 0.01: 0.5;
y = 5*x - log(x);
figure(1)
plot(x, y, 'k');
hold on;
%  设置迭代初始点
x = 0.35;
plot(x, (5*x - log(x)), 'ro');
for n = 1:5  %  限定迭代次数为5次
%  计算一阶导数数值:
dy = 5 - (1/x);
%  (由dy = 0可推知理论最优解为x = 0.2 )
hy = 1/(x^2);
%  计算下一次迭代的x值（牛顿-拉夫逊迭代公式）
xnew =x - (dy/hy);
x = xnew;
y =5*x - log(x);
plot([x, x], [0, y], 'b');
end;
