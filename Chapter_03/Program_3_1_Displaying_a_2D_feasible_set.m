% 例程 3.1  绘制二维可行解集
%  示例1
%  直线方程：ax + by = c
a1 = 8;
b1 = 10;
c1 = 80;
a2 = 18;
b2 = 14;
c2 = 252;
%  约束条件的交点坐标计算
X1 = c1/a1;
Y1 = c1/b1;
X2 = c2/a2;
Y2 = c2/b2;
figure(1)
%  绘制坐标轴
plot([-5 20], [0 0], 'b');
hold  on;
plot([0, 0], [-5, 20], 'b');
%  绘制可行解集（填充区域）
patch([0, 0, X2, X1], [Y1, Y2, 0, 0], 'g');
%  绘制约束直线
plot([0, X1], [Y1, 0], 'k');
plot([0, X2], [Y2, 0], 'k');
