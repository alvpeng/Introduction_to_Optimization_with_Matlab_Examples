% 例程 5.10 仓库问题示例（基础动态规划解法）
Cw = 0;  %  最优（最大）存储容量
%  货物出入库记录
L = [12, -3, 15, -6, 14, 30, -25, -3, 37, 4, -8, -14];
n = length(L);
C = zeros(n, n);  %  存储各区间[i, j]所需的存储容量
for i = 1: n
C(i, i) = 0;
for j = i + 1: n
C(i, j) = max([0, L(j - 1) + C(i, j - 1)]);
if (C(i, j) > Cw)
Cw = C(i, j);
end;
end;
end;
%  输出结果（所需的最大存储容量）
Cw
