% 例程 14.7  目标达到法示例
%  定义目标函数
fun = @(x) [x(1)^4 + x(2)^4 + x(1)*x(2) - (x(1)^2)*(x(2)^2) - 9*x(1)^2 + 25; ...
    x(1)^4 + x(2)^4 + x(1)*x(2) - (x(1)^2)*(x(2)^2) - 3*x(2)^2 + 5];
Jref = [5, 5];
weight = [1, 1];
x0 = [1, 1];
x = fgoalattain(fun, x0, Jref, weight);
%  输出结果
disp('决策空间中的解：')
x
disp('对应的帕雷托点：')
fun(x)
